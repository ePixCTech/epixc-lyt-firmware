int pixcHttpsPostJson(const char* url, const char* body, char* out, size_t cap, int* outLen, int timeoutMs) {
  if (outLen != nullptr) *outLen = 0;
  if (out != nullptr && cap > 0) out[0] = 0;
  if (!pixcUrlAllowed(url) || body == nullptr) return 0;

  esp_http_client_config_t cfg = {};
  pixcHttpsConfigure(cfg, url, timeoutMs);
  cfg.method = HTTP_METHOD_POST;

  esp_http_client_handle_t c = esp_http_client_init(&cfg);
  if (c == nullptr) return 0;
  esp_http_client_set_header(c, "Content-Type", "application/json");
  const int bodyLen = (int)strlen(body);
  if (esp_http_client_open(c, bodyLen) != ESP_OK) {
    ESP_LOGW(TAG, "provisioning refused: TLS failed - certificate did not chain to any pinned "
                  "root or is out of date, or the host is unreachable");
    esp_http_client_cleanup(c);
    return 0;
  }
  if (esp_http_client_write(c, body, bodyLen) != bodyLen) {
    esp_http_client_close(c);
    esp_http_client_cleanup(c);
    return 0;
  }
  esp_http_client_fetch_headers(c);
  const int status = esp_http_client_get_status_code(c);
  if (out != nullptr && cap > 1) {
    int got = 0;
    while (got < (int)cap - 1) {
      const int n = esp_http_client_read(c, out + got, (int)cap - 1 - got);
      if (n <= 0) break;
      got += n;
    }
    out[got] = 0;
    if (outLen != nullptr) *outLen = got;
  }
  esp_http_client_close(c);
  esp_http_client_cleanup(c);
  return status;
}
