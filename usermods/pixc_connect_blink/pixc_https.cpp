// This image's commit time (pio-scripts/pixc_build_id.py: committer time in minutes): the light's
// real time cannot be earlier, which is what lets a certificate be refused before SNTP answers.
static constexpr int64_t kTlsTimeFloor = static_cast<int64_t>(PIXC_FW_BUILD) * 60;

static int64_t x509Seconds(const mbedtls_x509_time& t) {
  return pixc::utcSeconds(t.year, t.mon, t.day, t.hour, t.min, t.sec);
}

// mbedTLS calls this for each certificate of the chain it verified, the pinned root at the top
// included (x509_crt_merge_flags_with_cb), after its own checks. Adding a flag fails the handshake
// with MBEDTLS_ERR_X509_CERT_VERIFY_FAILED, since verification is REQUIRED.
static int pixcVerifyDates(void*, mbedtls_x509_crt* crt, int depth, uint32_t* flags) {
  if (crt == nullptr || flags == nullptr) return MBEDTLS_ERR_X509_BAD_INPUT_DATA;
  const pixc::CertTime v = pixc::certTimeVerdict(x509Seconds(crt->valid_from), x509Seconds(crt->valid_to),
                                                 static_cast<int64_t>(time(nullptr)), kTlsTimeFloor);
  if (v == pixc::CertTime::Ok) return 0;
  *flags |= v == pixc::CertTime::NotYetValid ? MBEDTLS_X509_BADCERT_FUTURE : MBEDTLS_X509_BADCERT_EXPIRED;
  ESP_LOGW(TAG, "TLS refused: certificate %d of the chain is %s (valid %04d-%02d-%02d to %04d-%02d-%02d)%s",
           depth, v == pixc::CertTime::NotYetValid ? "not valid yet" : "expired",
           crt->valid_from.year, crt->valid_from.mon, crt->valid_from.day,
           crt->valid_to.year, crt->valid_to.mon, crt->valid_to.day,
           pixc::clockTrusted(time(nullptr), kTlsTimeFloor) ? "" : " - before this firmware was built");
  return 0;
}

// The pinned roots, parsed once and shared by every connection (esp-tls borrows a CA chain, never
// frees it; this framework has no MBEDTLS_DYNAMIC_FREE_CA_CERT). One copy in RAM instead of one
// per open connection, as `cert_pem` made. A failed parse is retried at the next connection.
static mbedtls_x509_crt* s_roots = nullptr;

static mbedtls_x509_crt* pinnedRoots() {
  static StaticSemaphore_t lockBuf;
  static SemaphoreHandle_t lock = xSemaphoreCreateMutexStatic(&lockBuf);   // C++ static init: once
  xSemaphoreTake(lock, portMAX_DELAY);
  if (s_roots == nullptr) {
    mbedtls_x509_crt* c = static_cast<mbedtls_x509_crt*>(calloc(1, sizeof(mbedtls_x509_crt)));
    if (c != nullptr) {
      mbedtls_x509_crt_init(c);
      // PEM: the length includes the terminating NUL. As esp-tls did for cert_pem: refused on an
      // error, kept (with a warning) when some certificates parsed and some did not.
      const int ret = mbedtls_x509_crt_parse(c, reinterpret_cast<const unsigned char*>(PIXC_TRUSTED_ROOTS),
                                             sizeof(PIXC_TRUSTED_ROOTS));
      if (ret < 0) {
        ESP_LOGE(TAG, "pinned roots did not parse (-0x%x): every TLS connection is refused", -ret);
        mbedtls_x509_crt_free(c);
        free(c);
        c = nullptr;
      } else {
        if (ret > 0) ESP_LOGW(TAG, "%d pinned root(s) did not parse", ret);
        s_roots = c;
      }
    }
  }
  mbedtls_x509_crt* out = s_roots;
  xSemaphoreGive(lock);
  return out;
}

void pixcTlsBegin() { pinnedRoots(); }

esp_err_t pixcTlsAttach(void* sslConf) {
  mbedtls_ssl_config* conf = static_cast<mbedtls_ssl_config*>(sslConf);
  if (conf == nullptr) return ESP_ERR_INVALID_ARG;
  mbedtls_ssl_conf_authmode(conf, MBEDTLS_SSL_VERIFY_REQUIRED);
  mbedtls_x509_crt* roots = pinnedRoots();
  // No roots, no CA chain: mbedTLS refuses the handshake (MBEDTLS_ERR_SSL_CA_CHAIN_REQUIRED).
  if (roots == nullptr) return ESP_FAIL;
  mbedtls_ssl_conf_ca_chain(conf, roots, nullptr);
  mbedtls_ssl_conf_verify(conf, pixcVerifyDates, nullptr);
  return ESP_OK;
}
