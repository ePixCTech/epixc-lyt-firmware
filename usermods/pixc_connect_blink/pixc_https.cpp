// esp_http_client picks its transport from the URL's scheme and ignores its TLS settings for http://, so
// an "http://" URL here would be fetched in plaintext through the very functions whose contract is
// "TLS against the pinned roots, no plaintext fallback". The provisioning URL is built https in a
// release image, but the OTA image and signature URLs arrive in the MQTT command; a release build
// refuses anything else here rather than trusting every caller to have checked (final
// pre-production audit, 2026-10-07). The signature would still stop a foreign image - this keeps
// the transport promise as well. Bench builds keep http for a local stack.
static bool pixcUrlAllowed(const char* url) {
  if (url == nullptr) return false;
#ifdef EPIXC_ALLOW_PLAINTEXT_PROVISION
  return true;
#else
  if (strncmp(url, "https://", 8) == 0) return true;
  ESP_LOGW(TAG, "refused: not an https:// URL");
  return false;
#endif
}

// Every TLS request this firmware makes is configured here, in one function, so the trust decision
// cannot drift between the provisioning fetch and the firmware download. Both are gated on the same
// pinned roots, and that is not a coincidence to be tidied away later — see the note on
// blast radius in pixc_connect_blink.cpp's runOta().
static void pixcHttpsConfigure(esp_http_client_config_t& cfg, const char* url, int timeoutMs) {
  cfg.url = url;
  // The one line that makes this worth doing. Without a CA (it was `cert_pem` until D411) the client
  // completes a handshake with any certificate, so an https:// URL on its own proves nothing at all.
  //
  // Pinned at the root rather than the leaf: the ISRG roots (X1, X2, YE, YR) for a Caddy-terminated
  // Let's Encrypt certificate, GTS Root R4 for Cloudflare's edge. Which one a device meets depends
  // on whether the DNS record is proxied, and on Let's Encrypt's chain of the day — see pixc_roots.h.
  // pixcTlsAttach sets those roots and the certificate date check (D411); `cert_pem` stays unset,
  // since esp-tls takes the attach hook instead of it, never both.
  cfg.crt_bundle_attach = pixcTlsAttach;
  cfg.timeout_ms = timeoutMs;
  // A redirect is another host answering the question this request exists to ask safely — which
  // broker to trust, or which bytes to flash. Following one silently would move the trust decision
  // to whoever controls the Location header.
  cfg.disable_auto_redirect = true;
  cfg.method = HTTP_METHOD_GET;
}

int pixcHttpsGet(const char* url, char* out, size_t cap) {
  if (!pixcUrlAllowed(url) || out == nullptr || cap < 2) return -1;

  esp_http_client_config_t cfg = {};
  pixcHttpsConfigure(cfg, url, 8000);

  esp_http_client_handle_t c = esp_http_client_init(&cfg);
  if (c == nullptr) return -1;

  int len = -1;
  const esp_err_t err = esp_http_client_open(c, 0);
  if (err != ESP_OK) {
    // Overwhelmingly a certificate that did not chain to the pinned root, or an unreachable host.
    // Named explicitly because the bare error code has sent people looking at Wi-Fi for hours.
    ESP_LOGW(TAG, "provisioning refused: TLS failed (%s) - certificate did not chain to any "
                  "pinned root or is out of date, or the host is unreachable", esp_err_to_name(err));
    esp_http_client_cleanup(c);
    return -1;
  }

  esp_http_client_fetch_headers(c);
  const int status = esp_http_client_get_status_code(c);
  if (status == 200) {
    const int n = esp_http_client_read(c, out, cap - 1);
    if (n > 0) {
      out[n] = 0;
      len = n;
    }
  } else {
    ESP_LOGW(TAG, "provisioning failed: HTTP %d", status);
  }

  esp_http_client_close(c);
  esp_http_client_cleanup(c);
  return len;
}

